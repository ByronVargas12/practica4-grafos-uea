import heapq
import time
import os

class GrafoVuelos:
    def __init__(self):
        self.adjacencia = {}

    def agregar_vuelo(self, origen: str, destino: str, precio: float):
        origen = origen.upper().strip()
        destino = destino.upper().strip()

        if origen not in self.adjacencia:
            self.adjacencia[origen] = []
        if destino not in self.adjacencia:
            self.adjacencia[destino] = []

        self.adjacencia[origen].append((destino, precio))

    def cargar_datos_demo(self):
        vuelos = [
            ("UIO", "GYE", 50.0),
            ("UIO", "BOG", 180.0),
            ("GYE", "LIM", 220.0),
            ("BOG", "LIM", 150.0),
            ("BOG", "MIA", 340.0),
            ("LIM", "MIA", 390.0),
            ("MIA", "MAD", 350.0),
            ("BOG", "MAD", 650.0)
        ]
        for ori, des, pre in vuelos:
            self.agregar_vuelo(ori, des, pre)

    def obtener_vuelos_reporte(self):
        reporte = []
        for origen, destinos in self.adjacencia.items():
            if destinos:
                conexiones = [f"{dest} (${precio:.2f})" for dest, precio in destinos]
                reporte.append(f"Desde [{origen}]: " + " | ".join(conexiones))
            else:
                reporte.append(f"Desde [{origen}]: Sin vuelos salientes")
        return "\n".join(reporte)

    def buscar_vuelo_mas_barato(self, origen: str, destino: str):
        origen = origen.upper().strip()
        destino = destino.upper().strip()

        if origen not in self.adjacencia or destino not in self.adjacencia:
            return None, [], 0.0

        inicio_tiempo = time.perf_counter()

        distancias = {nodo: float('inf') for nodo in self.adjacencia}
        distancias[origen] = 0
        predecesores = {nodo: None for nodo in self.adjacencia}
        pq = [(0, origen)]

        while pq:
            costo_actual, nodo_actual = heapq.heappop(pq)

            if nodo_actual == destino:
                break

            if costo_actual > distancias[nodo_actual]:
                continue

            for vecino, precio in self.adjacencia[nodo_actual]:
                nuevo_costo = costo_actual + precio
                if nuevo_costo < distancias[vecino]:
                    distancias[vecino] = nuevo_costo
                    predecesores[vecino] = nodo_actual
                    heapq.heappush(pq, (nuevo_costo, vecino))

        fin_tiempo = time.perf_counter()
        tiempo_ejecucion = fin_tiempo - inicio_tiempo

        if distancias[destino] == float('inf'):
            return None, [], tiempo_ejecucion

        ruta = []
        actual = destino
        while actual is not None:
            ruta.append(actual)
            actual = predecesores[actual]
        ruta.reverse()

        return distancias[destino], ruta, tiempo_ejecucion

# Crear e iniciar la aplicación
grafo = GrafoVuelos()
grafo.cargar_datos_demo()

print("="*50)
print("1. REPORTE DE ESTRUCTURA DE DATOS (LISTA DE ADYACENCIA)")
print("="*50)
print(grafo.obtener_vuelos_reporte())
print("\n" + "="*50)
print("2. BÚSQUEDA DE RUTA MÁS BARATA (UIO -> MAD)")
print("="*50)
costo, ruta, t_ejecucion = grafo.buscar_vuelo_mas_barato("UIO", "MAD")
print(f"Ruta encontrada: {' -> '.join(ruta)}")
print(f"Costo total: ${costo:.2f} USD")
print(f"Tiempo de ejecución: {t_ejecucion:.6f} segundos")